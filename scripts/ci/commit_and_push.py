#!/usr/bin/env python3
"""Commit and push a fixed set of paths when the working tree is dirty.

Replaces the inline shell block used by bot-authored maintenance workflows,
which configured a committer identity, tested `git status --porcelain` for
output, then staged, committed, and pushed. Keeping the branch here (ADR-006:
no logic in YAML) makes the dirty check and the no-op path testable.

The caller passes the paths to stage explicitly; this script never stages the
whole tree. `git status --porcelain` is evaluated against those paths only, so
an unrelated dirty file cannot trigger a commit that would then stage nothing.

Authentication is the caller's job (`gh auth setup-git` before this step). This
script only configures the committer identity for the local repository.

Two publish modes:

* Default: `git push` to the checked-out branch. This fails on a protected
  default branch for any identity outside the ruleset bypass list.
* `--branch NAME`: commit on NAME, push it, and open a pull request against
  `--base` with `gh pr create`. Use this where the default branch is protected
  (issue #7287). Rules:
    - A clean tree is a no-op.
    - An open pull request already tracking NAME is left alone and the run exits 0,
      so an unmerged pull request never gathers a second one.
    - A remote NAME with no open pull request is stale: it is deleted and
      recreated from the current checkout. Its content is regenerated by the
      caller on every run, so the delete loses nothing. Nothing is force-pushed.
  A pull request opened with `GITHUB_TOKEN` starts no `pull_request` runs, so a
  human must close and reopen it, or push to it, before required checks report.

EXIT CODES (ADR-035):
  0  - Success: committed and published, or nothing to commit, or a pull request
       already tracks the branch
  1  - Error: a git command failed
  2  - Error: usage/configuration (git or gh binary missing, bad argument)
  3  - Error: external service failure (`gh` could not list or create the pull request)
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys

EXIT_SUCCESS = 0
EXIT_GIT_FAILED = 1
EXIT_USAGE = 2
EXIT_EXTERNAL = 3

_BASE_DEFAULT = "main"
EXIT_NOT_FOUND_LS_REMOTE = 2  # `git ls-remote --exit-code`: no matching ref


def _git(args: list[str]) -> subprocess.CompletedProcess[str]:
    """Run a git command, capturing combined output as UTF-8 text."""
    return subprocess.run(
        ["git", *args],
        check=False,
        stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT,
        text=True,
        encoding="utf-8",
        errors="replace",
    )


def _run(args: list[str]) -> int:
    """Run a git command and report failures. Returns the git exit code."""
    result = _git(args)
    if result.returncode != 0:
        print(f"ERROR: git {' '.join(args)} failed:", file=sys.stderr)
        print(result.stdout, file=sys.stderr)
    return result.returncode


def dirty(paths: list[str]) -> bool:
    """Return True when `git status --porcelain` reports changes under paths."""
    result = _git(["status", "--porcelain", "--", *paths])
    if result.returncode != 0:
        raise RuntimeError(f"git status failed: {result.stdout}")
    return bool(result.stdout.strip())


class GhQueryError(RuntimeError):
    """`gh` could not answer a pull request query. Maps to EXIT_EXTERNAL."""


def _gh(args: list[str]) -> subprocess.CompletedProcess[str]:
    """Run a gh command, capturing combined output as UTF-8 text."""
    return subprocess.run(
        ["gh", *args],
        check=False,
        stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT,
        text=True,
        encoding="utf-8",
        errors="replace",
    )


def _fail(command: str, result: subprocess.CompletedProcess[str]) -> None:
    print(f"ERROR: {command} failed:", file=sys.stderr)
    print(result.stdout, file=sys.stderr)


def open_pr_url(branch: str) -> str | None:
    """Return the URL of the open same-repository pull request headed at `branch`, or None.

    `gh pr list --head` matches the head ref name only, so a fork pull request
    that reuses the branch name would match too and stop the job for good.
    Rows with `isCrossRepository` true are ignored.

    Raises GhQueryError when `gh` cannot answer, so a lookup failure is never
    read as "no pull request".
    """
    result = _gh(
        ["pr", "list", "--head", branch, "--state", "open", "--json", "url,isCrossRepository"]
    )
    if result.returncode != 0:
        raise GhQueryError(result.stdout)
    try:
        rows = json.loads(result.stdout)
    except json.JSONDecodeError as exc:
        raise GhQueryError(f"unparseable gh output: {result.stdout!r}") from exc
    if not isinstance(rows, list) or any(
        not isinstance(r, dict)
        or "url" not in r
        or not isinstance(r.get("isCrossRepository"), bool)
        for r in rows
    ):
        raise GhQueryError(f"unexpected gh output shape: {result.stdout!r}")
    own = [r for r in rows if not r["isCrossRepository"]]
    return str(own[0]["url"]) if own else None


def remote_branch_exists(branch: str) -> bool:
    """Return True when `origin` holds `branch`. Raises RuntimeError on a git failure."""
    result = _git(["ls-remote", "--exit-code", "--heads", "origin", branch])
    if result.returncode == 0:
        return True
    if result.returncode == EXIT_NOT_FOUND_LS_REMOTE:
        return False
    raise RuntimeError(f"git ls-remote failed: {result.stdout}")


def pr_body(paths: list[str], issue: str | None) -> str:
    """Build the pull request body. `## Changes` lists exactly the staged paths."""
    changes = "\n".join(f"- `{path}`" for path in paths)
    reference = f"Refs #{issue}" if issue else "none"
    lines = [
        "## Summary",
        "",
        "### What",
        "",
        "Scheduled workflow output committed on a bot branch.",
        "",
        "### Why",
        "",
        "The default branch is protected, so the workflow cannot push to it.",
        "Merge this pull request to publish the update.",
        "",
        "## Specification References",
        "",
        "| Type | Reference | Description |",
        "|------|-----------|-------------|",
        f"| **Issue** | {reference} | Scheduled workflow output |",
        "",
        "## Changes",
        "",
        changes,
        "",
        "## Type of Change",
        "",
        "- [x] Infrastructure/CI change",
    ]
    if issue:
        lines += ["", "## Related Issues", "", f"Refs #{issue}"]
    return "\n".join(lines) + "\n"


def _message_flags(messages: list[str]) -> list[str]:
    """Map each message paragraph to its own `-m` flag, in order."""
    return [flag for message in messages for flag in ("-m", message)]


def push_in_place(args: argparse.Namespace) -> int:
    """Stage, commit, and push on the checked-out branch."""
    for command in (
        ["add", "--", *args.path],
        ["commit", *_message_flags(args.message)],
        ["push"],
    ):
        if _run(command) != 0:
            return EXIT_GIT_FAILED
    print("Changes committed and pushed")
    return EXIT_SUCCESS


def publish_branch(args: argparse.Namespace) -> int:
    """Commit on a bot branch, push it, and open a pull request."""
    existing = open_pr_url(args.branch)
    if existing:
        print(f"Open pull request already tracks {args.branch}: {existing}")
        return EXIT_SUCCESS

    if remote_branch_exists(args.branch):
        print(f"Deleting stale remote branch {args.branch} (no open pull request)")
        if _run(["push", "origin", "--delete", args.branch]) != 0:
            return EXIT_GIT_FAILED

    for command in (
        ["checkout", "-B", args.branch],
        ["add", "--", *args.path],
        ["commit", *_message_flags(args.message)],
        ["push", "--set-upstream", "origin", args.branch],
    ):
        if _run(command) != 0:
            return EXIT_GIT_FAILED

    created = _gh(
        [
            "pr",
            "create",
            "--base",
            args.base,
            "--head",
            args.branch,
            "--title",
            args.pr_title or args.message[0],
            "--body",
            pr_body(args.path, args.issue),
        ]
    )
    if created.returncode != 0:
        _fail("gh pr create", created)
        return EXIT_EXTERNAL
    print(created.stdout.strip())
    return EXIT_SUCCESS


def build_parser() -> argparse.ArgumentParser:
    """Build the argument parser for the commit-and-push helper."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--path",
        action="append",
        required=True,
        help="Path to stage and watch for changes. Repeatable.",
    )
    parser.add_argument(
        "--message",
        action="append",
        required=True,
        help="Commit message paragraph, in order. Repeatable (maps to git -m).",
    )
    parser.add_argument("--user-name", required=True, help="git user.name to set.")
    parser.add_argument("--user-email", required=True, help="git user.email to set.")
    parser.add_argument(
        "--branch",
        help="Publish on this branch and open a pull request instead of pushing in place.",
    )
    parser.add_argument(
        "--base", default=_BASE_DEFAULT, help="Pull request base branch (with --branch)."
    )
    parser.add_argument(
        "--pr-title", help="Pull request title (with --branch). Defaults to the first --message."
    )
    parser.add_argument(
        "--issue", help="Issue number for a `Refs #N` line in the pull request body."
    )
    return parser


def main(argv: list[str] | None = None) -> int:
    """Commit and push the given paths when dirty. Returns an ADR-035 code."""
    args = build_parser().parse_args(argv)

    try:
        for key, value in (("user.name", args.user_name), ("user.email", args.user_email)):
            if _run(["config", key, value]) != 0:
                return EXIT_GIT_FAILED

        if not dirty(args.path):
            print(f"No changes to commit (examined {len(args.path)} path(s))")
            return EXIT_SUCCESS

        return publish_branch(args) if args.branch else push_in_place(args)
    except FileNotFoundError as exc:
        print(f"ERROR: git not available (or gh, with --branch): {exc}", file=sys.stderr)
        return EXIT_USAGE
    except GhQueryError as exc:
        print(f"ERROR: gh pr list failed: {exc}", file=sys.stderr)
        return EXIT_EXTERNAL
    except RuntimeError as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return EXIT_GIT_FAILED


if __name__ == "__main__":
    sys.exit(main())
