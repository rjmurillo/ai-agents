#!/usr/bin/env python3
"""Build and post the escalated AI issue triage PRD comment."""

from __future__ import annotations

import os
import subprocess
import sys
from pathlib import Path

CONFIG_ERROR = 2
DEFAULT_OUTPUT = Path(os.environ.get("RUNNER_TEMP", ".")) / "prd-comment.md"


def _prd_depth(complexity_score: int) -> str:
    if complexity_score >= 10:
        return "Comprehensive"
    if complexity_score >= 7:
        return "Detailed"
    return "Standard"


def build_prd_comment(
    *,
    prd_content: str,
    complexity_score: str,
    escalation_criteria: str,
    repository: str,
    server_url: str,
    run_id: str,
) -> str:
    score = int(complexity_score)
    prd_depth = _prd_depth(score)
    footer = (
        f"<sub>Generated by [AI PRD Generation](https://github.com/{repository}) "
        f"| [View Workflow]({server_url}/{repository}/actions/runs/{run_id})</sub>"
    )
    return f"""<!-- AI-PRD-GENERATION -->

## Product Requirements Document

> [!IMPORTANT]
> This PRD was automatically generated based on issue triage escalation.
> **Complexity Score**: {complexity_score}/12 ({prd_depth})
> **Escalation Criteria**: {escalation_criteria}

<details>
<summary>About this PRD</summary>

This PRD was generated by the **Explainer Agent** after the issue was flagged
for detailed analysis. The document is designed to be self-contained - it can
be passed to a separate AI agent instance for implementation without additional
context.

**PRD Depth Levels**:
- **Standard** (4-6): Brief analysis, clear requirements
- **Detailed** (7-9): Research section, blocking questions
- **Comprehensive** (10-12): Phased implementation, risk analysis

</details>

---

{prd_content}
---

{footer}"""


def post_comment(*, issue_number: str, body_file: Path) -> int:
    sys.stdout.flush()
    result = subprocess.run(
        [
            "python3",
            ".github/scripts/run_with_retry.py",
            "--",
            "python3",
            ".github/scripts/post_issue_comment.py",
            "--issue",
            issue_number,
            "--body-file",
            str(body_file),
            "--marker",
            "AI-PRD-GENERATION",
        ],
        check=False,
    )
    return result.returncode


def main(argv: list[str] | None = None) -> int:
    if argv:
        print("::error::unexpected command line arguments", file=sys.stderr)
        return CONFIG_ERROR
    issue_number = os.environ.get("ISSUE_NUMBER", "")
    if not issue_number:
        print("::error::ISSUE_NUMBER is required", file=sys.stderr)
        return CONFIG_ERROR
    output = DEFAULT_OUTPUT
    try:
        comment = build_prd_comment(
            prd_content=os.environ.get("PRD_CONTENT", ""),
            complexity_score=os.environ.get("COMPLEXITY_SCORE", ""),
            escalation_criteria=os.environ.get("ESCALATION_CRITERIA", ""),
            repository=os.environ.get("GITHUB_REPOSITORY", ""),
            server_url=os.environ.get("SERVER_URL", ""),
            run_id=os.environ.get("RUN_ID", ""),
        )
    except ValueError:
        print("::error::COMPLEXITY_SCORE must be an integer", file=sys.stderr)
        return CONFIG_ERROR
    output.write_text(comment + "\n", encoding="utf-8")
    return post_comment(issue_number=issue_number, body_file=output)


if __name__ == "__main__":
    raise SystemExit(main())
