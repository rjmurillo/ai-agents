"""Resolve each run's workflow definition from the ref GitHub will evaluate.

Issue #4835, Copilot review on PR #5357. The guard verifies that a cancelled
required context can be regenerated by reading the workflow's ``on:`` block.
Reading it from one local checkout answers for one ref: whichever commit that
checkout happens to sit on. GitHub does not use that ref.

For a pull_request-family event, GitHub evaluates the workflow file as it
stands on the pull request's merge ref, so every open pull request can carry a
different version of the same file. A pull request that drops ``reopened`` from
its ``pull_request: types:`` list therefore verified against a healthy local
definition, passed, and was cancelled with no working recovery route. That is
the exact class issue #4827 fixed by hand and #4835 exists to make detectable,
reappearing one level up.

This module fetches the definition per run, at ``refs/pull/<n>/merge``, keyed
by the run's own ``path`` (the Actions run payload names the file that produced
it, which also removes the shared-``name:`` ambiguity on this path). The result
is combined with the base-branch definition by
:func:`~scripts.github_core.workflow_event_subscriptions.pin_to_head_ref`,
which takes the pull_request activity types from the head ref and requires
``workflow_dispatch`` on both.

Cost: one contents call per distinct (ref, path) pair. The jobs endpoint
already costs one call per run, so a 41-PR batch over three workflows goes from
about 123 reads to about 246. Every failure to resolve, including a pull
request with no merge ref because it conflicts, records None and blocks the run
rather than falling back to the local corpus.
"""

from __future__ import annotations

import base64
import binascii
from collections.abc import Mapping, Sequence
from typing import Any
from urllib.parse import quote

import yaml

from scripts.github_core.protocol import GitHubClient
from scripts.github_core.recovery_manifest import WorkflowRun
from scripts.github_core.workflow_event_subscriptions import (
    WorkflowSubscriptions,
    parse_workflow_subscriptions,
    pin_to_head_ref,
)

__all__ = [
    "fetch_workflow_document",
    "merge_ref",
    "resolve_run_subscriptions",
]


def merge_ref(pr_number: int) -> str:
    """The ref GitHub evaluates a pull_request-family workflow trigger against.

    ``refs/pull/<n>/merge`` lives in the base repository even for a fork pull
    request, so one repository argument covers both cases. It is absent while
    the pull request conflicts, which surfaces as a failed fetch and therefore
    as a blocked run: a pull request GitHub cannot merge is also one it will not
    produce recovery runs for.
    """
    return f"refs/pull/{pr_number}/merge"


def fetch_workflow_document(
    client: GitHubClient, repository: str, path: str, ref: str
) -> Mapping[str, Any] | None:
    """Read one workflow file at one ref, or None when it cannot be read.

    None covers every reason the definition is unavailable: the transport
    failed, the ref or the path does not exist, the content is not base64, the
    bytes are not UTF-8, the YAML does not parse, or the document is not a
    mapping. Callers must treat all of them the same way, as "unverifiable",
    never as "no subscriptions" or "fall back to the local copy".
    """
    endpoint = (
        f"repos/{quote(repository, safe='/')}/contents/{quote(path, safe='/')}"
        f"?ref={quote(ref, safe='')}"
    )
    try:
        payload = client.rest_get(endpoint)
    except (RuntimeError, OSError, ValueError):
        return None
    if not isinstance(payload, Mapping):
        return None
    content = payload.get("content")
    if payload.get("encoding") != "base64" or not isinstance(content, str):
        return None
    try:
        text = base64.b64decode(content, validate=False).decode("utf-8")
    except (binascii.Error, UnicodeDecodeError, ValueError):
        return None
    try:
        document = yaml.safe_load(text)
    except yaml.YAMLError:
        return None
    return document if isinstance(document, Mapping) else None


def resolve_run_subscriptions(
    client: GitHubClient,
    repository: str,
    runs: Sequence[WorkflowRun],
    *,
    base_subscriptions: Mapping[str, WorkflowSubscriptions],
) -> dict[int, WorkflowSubscriptions | None]:
    """Map each run id to the definition GitHub will evaluate for its PR.

    Args:
        client: Transport used for the contents reads. No writes happen here.
        repository: ``owner/repo`` of the base repository, which is where the
            pull request merge refs live.
        runs: The runs to resolve. A run with no ``workflow_path`` maps to
            None: without the file name there is nothing to fetch, and the
            workflow ``name:`` cannot stand in for it because two files may
            declare one name.
        base_subscriptions: The base branch's corpus, keyed by name and
            filename, used only for the ``workflow_dispatch`` half of
            :func:`pin_to_head_ref`.

    Returns:
        One entry per run id, so no run silently falls back to the name map.
        The value is None when the definition could not be resolved, which
        blocks that run.
    """
    documents: dict[tuple[str, str], WorkflowSubscriptions | None] = {}
    resolved: dict[int, WorkflowSubscriptions | None] = {}

    for run in runs:
        if not run.workflow_path:
            resolved[run.run_id] = None
            continue
        key = (merge_ref(run.pr_number), run.workflow_path)
        if key not in documents:
            documents[key] = _parse_at_ref(
                client, repository, key, base_subscriptions
            )
        resolved[run.run_id] = documents[key]
    return resolved


def _parse_at_ref(
    client: GitHubClient,
    repository: str,
    key: tuple[str, str],
    base_subscriptions: Mapping[str, WorkflowSubscriptions],
) -> WorkflowSubscriptions | None:
    """Fetch, parse, and pin one workflow file at one ref."""
    ref, path = key
    document = fetch_workflow_document(client, repository, path, ref)
    if document is None:
        return None
    filename = path.rsplit("/", 1)[-1]
    head = parse_workflow_subscriptions(document, fallback_name=filename)
    return pin_to_head_ref(head, base_subscriptions.get(filename))
